const DICT = { en: EN, ru: RU };
let lang = 'en';
const subs = new Set();

export function getLang() { return lang; }

export function setLang(next, { save = true } = {}) {
  if (!LANGS.includes(next)) return lang;
  lang = next;
  if (save) { try { localStorage.setItem(KEY, next); } catch {} }
  document.documentElement.lang = next;
  document.documentElement.dir = 'ltr';
  for (const fn of subs) fn(next);
  applyDom();
  return lang;
}

export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem(KEY); } catch {}
  const auto = (navigator.language || 'en').toLowerCase().startsWith('ru') ? 'ru' : 'en';
  setLang(LANGS.includes(saved) ? saved : auto, { save: false });
  return lang;
}

// t('run.room', { code: 'AB12' })
export function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) ?? EN[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function onChange(fn) { subs.add(fn); return () => subs.delete(fn); }

// static markup: <span data-i18n="menu.solo">, <input data-i18n-ph="menu.codePlaceholder">
export function applyDom(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}

